/**
 * 判断身强身弱（简化版）
 * @param wuxing 五行统计
 * @param dayGan 日干
 */
export function isStrongBody(wuxing: { gold: number; wood: number; water: number; fire: number; earth: number }, dayGan: string): boolean {
  // 日干五行
  const ganWuxing: Record<string, string> = {
    '甲': '木', '乙': '木',
    '丙': '火', '丁': '火',
    '戊': '土', '己': '土',
    '庚': '金', '辛': '金',
    '壬': '水', '癸': '水'
  };
  
  const dayWuxing = ganWuxing[dayGan];
  if (!dayWuxing) return true;
  
  // 计算生助日干的五行数量
  const wuxingMap: Record<string, number> = {
    '金': wuxing.gold,
    '木': wuxing.wood,
    '水': wuxing.water,
    '火': wuxing.fire,
    '土': wuxing.earth
  };
  
  // 生助关系：木生火、火生土、土生金、金生水、水生木
  const shengZhu: Record<string, string> = {
    '木': '水',
    '火': '木',
    '土': '火',
    '金': '土',
    '水': '金'
  };
  
  const dayCount = wuxingMap[dayWuxing];
  const shengZhuCount = wuxingMap[shengZhu[dayWuxing]] || 0;
  
  // 日干 + 生助 > 4 为身强
  return dayCount + shengZhuCount > 4;
}
